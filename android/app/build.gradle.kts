    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }

    // The telephony/audio unit tests exercise pure logic, but some of it sits in
    // files that also reference android.* constants. Returning defaults keeps
    // those from throwing "not mocked" instead of running the assertion.
    testOptions {
        unitTests.isReturnDefaultValues = true
    }

    // The cross-language protocol fixtures live at the repository root, outside
    // the Gradle build, because Node and (from W2) .NET read the very same
    // files. Mounting them as unit-test resources is what lets the Kotlin
    // implementation be held to the identical vectors rather than to a copy that
    // can quietly drift. See protocol/README.md.
    sourceSets {
        getByName("test") {
            resources.srcDir(rootProject.file("../protocol/fixtures"))
        }
    }

    buildTypes {
        debug {
            // 10.0.2.2 = host loopback from the Android emulator (default only)
            buildConfigField("String", "SIGNALING_URL", "\"$debugSignalingUrl\"")
        }
        release {
            isMinifyEnabled = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            buildConfigField("String", "SIGNALING_URL", "\"$releaseSignalingUrl\"")
        }
    }
}

