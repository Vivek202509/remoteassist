/**
 * Signaling endpoint, overridable per build without editing this file:
 *
 *   ./gradlew assembleDebug -PsignalingUrl=wss://signal.example.com
 *
 * The debug default is the Android emulator's alias for host loopback. It is
 * NOT reachable from a physical handset, so any real-device test (A03 or Vivo)
 * must pass -PsignalingUrl pointing at a server both phones can reach over the
 * internet. Leaving it hardcoded is why a debug APK sideloaded onto the A03
 * could never connect.
 */
val signalingUrlOverride: String? = project.findProperty("signalingUrl") as String?
val debugSignalingUrl = signalingUrlOverride ?: "ws://10.0.2.2:8080"
val releaseSignalingUrl = signalingUrlOverride ?: "wss://signal.yourdomain.com"

/**
 * Cleartext is denied by default from API 28 on, so a debug build pointed at a
 * plain `ws://` broker fails to connect at all — silently, because OkHttp's
 * failure surfaces as a reconnect rather than an error the tester can see.
 *
 * The generated config below re-permits cleartext for exactly one host: the one
 * `-PsignalingUrl` names, and only when that URL is `ws://`. It is applied from
 * `src/debug/AndroidManifest.xml`, so a release build keeps the platform default
 * and no shipped artifact ever carries a cleartext exemption.
 */
val debugCleartextHost: String? =
    Regex("^ws://([^:/?#]+)").find(debugSignalingUrl)?.groupValues?.get(1)

abstract class GenerateNetworkSecurityConfig : DefaultTask() {
    /** Host allowed to speak cleartext. Absent means: allow nothing. */
    @get:Input @get:Optional abstract val cleartextHost: Property<String>

    @get:OutputDirectory abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val host = cleartextHost.orNull
        val exemption = if (host == null) "" else """
            |    <domain-config cleartextTrafficPermitted="true">
            |        <domain includeSubdomains="false">$host</domain>
            |    </domain-config>
        """.trimMargin()
        val xmlDir = outputDirectory.get().asFile.resolve("xml").apply { mkdirs() }
        xmlDir.resolve("network_security_config.xml").writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- GENERATED by :app:generateDebugNetworkSecurityConfig — do not edit. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false"/>
            |$exemption
            |</network-security-config>
            |
            """.trimMargin()
        )
    }
}

androidComponents {
    onVariants { variant ->
        if (variant.buildType != "debug") return@onVariants
        val task = tasks.register<GenerateNetworkSecurityConfig>(
            "generate${variant.name.replaceFirstChar { it.uppercase() }}NetworkSecurityConfig"
        ) {
            debugCleartextHost?.let { cleartextHost.set(it) }
        }
        variant.sources.res?.addGeneratedSourceDirectory(
            task, GenerateNetworkSecurityConfig::outputDirectory
        )
    }
}

